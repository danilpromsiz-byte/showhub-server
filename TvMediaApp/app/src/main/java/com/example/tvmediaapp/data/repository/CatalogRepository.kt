    fun getCatalog(): Flow<List<MovieCategory>> = flow {
        // Instant emit of cached items for zero startup latency
        emit(listOf(
            MovieCategory(id = "popular", title = "?????????? ??????", movies = sampleMovies),
            MovieCategory(id = "top_rated", title = "??????? ???????", movies = sampleMovies.sortedByDescending { it.rating })
        ))

        // Live catalog from server
        try {
            val liveMovies = ShowHubApiClient.fetchCatalog("all")
            if (liveMovies.isNotEmpty()) {
                val liveCategories = listOf(
                    MovieCategory(id = "popular", title = "?????????? ?? ShowHub", movies = liveMovies.take(24)),
                    MovieCategory(id = "top_rated", title = "??????? ???????", movies = liveMovies.sortedByDescending { it.rating }.take(24)),
                    MovieCategory(id = "demo", title = "????????? HLS / 4K ??????", movies = sampleMovies)
                )
                emit(liveCategories)
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

